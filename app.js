function calcularRecomendaciones() {
  // --- Lectura de parámetros ---
  const year = parseInt(document.getElementById('year').value) || 2025;
  const month = parseInt(document.getElementById('month').value) || 8;
  const day = parseInt(document.getElementById('day').value) || 18;
  const topN = parseInt(document.getElementById('topN').value) || 3;

  // Validar fecha futura
  const hoy = new Date();
  const fechaSeleccionada = new Date(year, month - 1, day);
  if (fechaSeleccionada > hoy) {
    alert("⚠️ No se pueden analizar fechas futuras");
    return;
  }

  const fechaTarget = `${year}-${pad(month)}-${pad(day)}`;

  // --- 1. Filtrar datos por fecha exacta ---
  const filtrados = HISTORIC_DATA.filter(r => r.date === fechaTarget);

  if (filtrados.length === 0) {
    document.getElementById('top3-cards').innerHTML = `
      <div class="empty-state">
        ⚠️ No hay sorteos registrados para la fecha ${fechaTarget}.
        <br><small>Intenta con otra fecha.</small>
      </div>
    `;
    document.getElementById('detalle-top3').innerHTML = '';
    document.getElementById('ranking-body').innerHTML = '';
    document.getElementById('total-sort').textContent = '0';
    document.getElementById('total-nums').textContent = '0';
    document.getElementById('media-esperada').textContent = '0';
    return;
  }

  // --- 2. Calcular FRECUENCIA ABSOLUTA (Fj) ---
  const freqMap = new Map();
  filtrados.forEach(r => {
    r.numbers.forEach(n => {
      const key = pad(parseInt(n));
      freqMap.set(key, (freqMap.get(key) || 0) + 1);
    });
  });

  // --- 3. Ordenar datos por fecha (para atraso correcto) ---
  const datosOrdenados = [...HISTORIC_DATA].sort((a, b) => a.date.localeCompare(b.date));
  const idxTarget = datosOrdenados.findIndex(r => r.date === fechaTarget);

  // --- 4. Calcular ÍNDICE DE ATRASO (Ai) ---
  const atrasoMap = new Map();
  for (let i = 0; i < 100; i++) {
    const num = pad(i);
    let ultimaAparicion = -1;

    // Buscar la última aparición antes de la fecha target
    for (let j = 0; j < idxTarget; j++) {
      if (datosOrdenados[j].numbers.includes(num)) {
        ultimaAparicion = j;
      }
    }

    if (ultimaAparicion >= 0) {
      const atraso = idxTarget - ultimaAparicion - 1;
      atrasoMap.set(num, atraso);
    } else {
      atrasoMap.set(num, idxTarget + 1);
    }
  }

  // --- 5. Calcular SCORE con factor de confianza ---
  const scores = [];
  for (const [num, freq] of freqMap.entries()) {
    const atraso = atrasoMap.get(num) || 0;
    const confianza = freq > 0 ? 1 : 0.5;
    const score = (freq * 0.6 * confianza) + (atraso * 0.4);
    scores.push({ numero: num, frecuencia: freq, atraso, score });
  }

  // Agregar números con frecuencia 0 pero con atraso
  for (let i = 0; i < 100; i++) {
    const num = pad(i);
    if (!freqMap.has(num)) {
      const atraso = atrasoMap.get(num) || 0;
      const score = (0 * 0.6 * 0.5) + (atraso * 0.4);
      scores.push({ numero: num, frecuencia: 0, atraso, score });
    }
  }

  // --- 6. Filtrar y ordenar ---
  const scoresFiltrados = scores.filter(s => s.score > 0);
  scoresFiltrados.sort((a, b) => b.score - a.score);

  // --- 7. Calcular desviación de la media (Poisson) ---
  const totalApariciones = freqMap.size;
  const mediaEsperada = totalApariciones / 100;
  const poissonMap = new Map();
  for (const [num, freq] of freqMap.entries()) {
    const desviacion = (freq - mediaEsperada) / Math.sqrt(mediaEsperada || 1);
    poissonMap.set(num, desviacion);
  }

  // --- 8. Actualizar estadísticas resumen ---
  document.getElementById('total-sort').textContent = filtrados.length;
  document.getElementById('total-nums').textContent = freqMap.size;
  document.getElementById('media-esperada').textContent = mediaEsperada.toFixed(2);

  // --- 9. Renderizar TOP 3 ---
  const container = document.getElementById('top3-cards');
  const detalle = document.getElementById('detalle-top3');
  const top = scoresFiltrados.slice(0, topN);

  // Calcular probabilidad sobre el top 20
  const top20 = scoresFiltrados.slice(0, 20);
  const totalTopScore = top20.reduce((acc, s) => acc + s.score, 0);

  if (top.length === 0) {
    container.innerHTML = `<div class="empty-state">No hay números con score > 0.</div>`;
    detalle.innerHTML = '';
    return;
  }

  let cardsHtml = '';
  let detalleHtml = '<div style="display:flex; flex-direction:column; gap:8px;">';

  top.forEach((item, index) => {
    const badgeClass = index === 0 ? 'top1' : index === 1 ? 'top2' : 'top3';
    const prob = totalTopScore > 0 ? ((item.score / totalTopScore) * 100) : 0;
    const desviacion = poissonMap.get(item.numero) || 0;
    const estado = desviacion > 1.96 ? '🔥 CALIENTE' : desviacion < -1.96 ? '❄️ FRÍO' : '⚖️ NEUTRAL';

    const justificacion =
      `Número ${item.numero}: Frecuencia histórica = ${item.frecuencia}, ` +
      `atraso = ${item.atraso} sorteos. Desviación Poisson = ${desviacion.toFixed(2)} (${estado}).`;

    cardsHtml += `
      <div class="top-card">
        <div class="top-inner">
          <span class="num-badge ${badgeClass}">${item.numero}</span>
          <div class="info">
            <div class="rank">#${index + 1}</div>
            <div class="score">Score ${item.score.toFixed(2)}</div>
          </div>
          <div class="prob-badge">${prob.toFixed(1)}%</div>
        </div>
      </div>
    `;

    detalleHtml += `
      <div class="justify">
        <strong>🔹 ${item.numero}</strong> — ${justificacion}
        <span style="display:block; margin-top:4px; font-size:13px; color:#334155;">
          Probabilidad relativa: <span class="prob">${prob.toFixed(2)}%</span> (sobre top 20).
        </span>
      </div>
    `;
  });

  container.innerHTML = cardsHtml;
  detalleHtml += '</div>';
  detalle.innerHTML = detalleHtml;

  // --- 10. Renderizar Ranking Combinado (Tabla) ---
  const rankingBody = document.getElementById('ranking-body');
  let rows = '';
  top20.forEach((item, idx) => {
    const prob = totalTopScore > 0 ? ((item.score / totalTopScore) * 100) : 0;
    const desviacion = poissonMap.get(item.numero) || 0;
    const badgeClass = desviacion > 1.96 ? 'hot-badge' : desviacion < -1.96 ? 'cold-badge' : 'neutral-badge';
    rows += `
      <tr>
        <td><strong>${idx + 1}</strong></td>
        <td><span class="num-badge-sm ${badgeClass}">${item.numero}</span></td>
        <td>${item.frecuencia}</td>
        <td>${item.atraso}</td>
        <td>${desviacion.toFixed(2)}</td>
        <td><strong>${item.score.toFixed(2)}</strong></td>
        <td>${prob.toFixed(1)}%</td>
      </tr>
    `;
  });
  rankingBody.innerHTML = rows;

  // Actualizar badge de datos
  document.getElementById('data-info').textContent =
    `📊 ${HISTORIC_DATA.length} registros · Fecha filtrada: ${fechaTarget}`;
}

